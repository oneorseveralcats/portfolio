from collections.abc import Iterable # used in a conditional to check input in BinaryTree constructor

import sys # parse commandline arguments to display testing information when "debug" is supplied
import unittest # used to write unit tests.

class TreeNode:
    def __init__(self, value):
        self.value = value
        self.left_node = None
        self.right_node = None
        self.size = 0  # Number of nodes in the subtree rooted at this node

        self.parent = None # added to make deleting/updating the tree easier.
        # the implementation otherwise relies on targeting the "parent of..." particular nodes
        # instead of the nodes themselves which feels less readable.
        
        self.height = 0 # added to make code cleaner. otherwise i would just generate height on the
        # fly, zip it up with a list of the nodes then operate on those tuples.

class BinaryTree:
    def __init__(self, values=None):
        """Constructor for BinaryTree class, either creates an empty binary tree or one populated with
           value(s) provided"""

        self.root = None

        if values:
            self.insert(values)
        




    ############################
    # General Helper Functions #
    ############################
    def node_gen(self, order="inorder"):
        """Returns a generator that will traverse the BinaryTree based on the order supplied. Allowed
           values for order: inorder, preorder, postorder, level"""

        # if there's a single element, generator supplies that single element and ceases.
        if self.root and self.root.size == 0:
            yield self.root
        else:
            match order:
                case "inorder": yield from self._node_gen_inorder(self.root)
                case "preorder": yield from self._node_gen_preorder(self.root)
                case "postorder": yield from self._node_gen_postorder(self.root)
                case "level": yield from self._node_gen_level()

    def _node_gen_inorder(self, node):
        """Generator that returns the subtree starting at "node" using the inorder traversal strategy"""

        if node:
            yield from self._node_gen_inorder(node.left_node)
            yield node
            yield from self._node_gen_inorder(node.right_node)

    def _node_gen_preorder(self, node):
        """Generator that returns the subtree starting at "node" using the preorder traversal strategy"""

        if node:
            yield node
            yield from self._node_gen_preorder(node.left_node)
            yield from self._node_gen_preorder(node.right_node)

    def _node_gen_postorder(self, node):
        """Generator that returns the subtree starting at "node" using the postorder traversal strategy"""

        if node:
            yield from self._node_gen_postorder(node.left_node)
            yield from self._node_gen_postorder(node.right_node)
            yield node

    # This feels janky and I kind of hate it. It essentially just sorts the nodes generated by the
    # inorder generator based on their height. It feels unbecoming of a generator because generators
    # seem like they're supposed to only evaluate up until they produce the next value then wait to
    # be called again, but this one consumes the entire inorder generator then produces values from
    # that.
    def _node_gen_level(self):
        """Generator that returns the subtree from the root node using the level-based traversal
           strategy"""

        yield from sorted(self._node_gen_inorder(self.root), key=lambda x: x.height)

    # this approach felt pretty brittle because it relies on sorted to be stable in its output order,
    # but the sorted function appears to be stable. From the python docs:
    #
    # > The built-in sorted() function is guaranteed to be stable. A sort is stable if it guarantees
    # > not to change the relative order of elements that compare equal — this is helpful for sorting
    # > in multiple passes (for example, sort by department, then by salary grade).
    # >
    # > https://docs.python.org/3/library/functions.html#sorted
    #
    # Even if the sorting order were to change, it would cause test cases to fail, so we okay :)


    # because of how frequently i just want a list of the values in a tree, i created a function to
    # convert the node generators to just a list of their values. this is mostly used in unit tests.
    def values_to_list(self, order="inorder"):
        """Returns a list of all the values in the BinaryTree according to the "order" used """

        return list(map(lambda x: x.value, self.node_gen(order)))
        

    # uses the generator defined above and a contraint to find the first (and only) node that has the
    # value being searched for. Used in find and delete. If not found, returns None.
    def find_node(self, value):
        """Returns a node with the value supplied, otherwise returns None"""

        return next((x for x in self.node_gen()
                       if x and x.value == value), None)


                


    ##########
    # Insert #
    ##########
    
    def insert(self, values):
        """Inserts a single value or list of values into BinaryTree while ignoring duplicate values"""

        if not self.find(values):
            if isinstance(values, Iterable):
                for i in values:
                    self._insert(i)
            else:
                self._insert(values)

    # literally the only loop in my implementation! aside from questions of mutability, this is a
    # pretty functional implementation. I could replace the loop with recursive calls that decapitate
    # the list until it's empty, each iteration calling insert on the head of the list. Could also
    # use map/filter just for their effects, but they would require being wrapped in list() because
    # they're iterators which are lazily evaluated.
    #
    # Sometimes a for loop is just the best option :)



    # where the real work happens. if the tree is empty, the inserted value becomes the root node.
    # otherwise it will call a helper function that determines where the new node should be inserted
    # while also contructing a new node with the value being inserted.
    #
    # It then proceeds to insert it on the right side of the parent, then give the child node a pointer
    # to its parent, calculates the height of the child node, then increments the size of the parent.
    def _insert(self, value):
        """Finds the proper insertion point and inserts a node into BinaryTree with the value supplied"""

        if self.root is None:
            self.root = TreeNode(value)
        else:
            if (parent := self._get_insertion_point()) and (child := TreeNode(value)):
                if parent.size == 0:
                    parent.left_node = child

                elif parent.size == 1:
                    parent.right_node = child

                child.parent = parent
                child.height = self._get_height(child)

                parent.size += 1

    # it seems like the standard way to name internal functions in python is beginning with _
    # see: https://peps.python.org/pep-0008/#descriptive-naming-styles


    def _get_insertion_point(self):
        """Returns the node where an insertion should occur in order to maintain a complete binary tree"""

        return self._get_sorted_insertion_points()[0]


    def _get_sorted_insertion_points(self):
        """Returns a list of leaf and non-full branch nodes in the order in which insertion should
           occur in order to maintain a complete binary tree"""

        # uses the inorder generator to return nodes that have one or less children then sorts them
        # based on height.
        return sorted([x for x in self.node_gen(order="inorder")
                         if x.size < 2], key=lambda x: x.height)

    # The reason for the sort can be demonstrated with this tree:
    # 
    #    1
    #  2   3 
    # 4 5
    #
    # The unsorted generator would return the nodes in the order "4, 5, 3" because that's the traversal
    # order. 3 is where the insertion should happen though, and the sorting makes sure that it is the
    # head of list
    #
    # If you have a tree like:
    #  1
    # 2 3
    #
    # the sorting operation won't do anything because 2 and 3 have the same height, so the insertion
    # pont is still correct.


    def _get_height(self, node):
        """Returns the height of the current node"""

        # recurses through the chain of parent pointers until a node doesn't have a parent pointer
        # while adding 1 each recursion.
        return 1 + self._get_height(node.parent) if node.parent else 0


       
    


    ########
    # Find #
    ########

    # wrapper to supply the self.root node to _find. This wrapper is very unnecessary but I like
    # having the user-facing function to be, essentially, a stable interface that hides the underlying
    # implementation
    def find(self, value):
        """Returns true if a node in the BinaryTree has the value being search for"""

        return self._find(value)
        
    # originally i had this implemented to do the searching itself, but it seemed reasonable that a
    # binary tree would have a function to find and return a node so i've piggybacked on that function
    # if find_node returns a node then _find return true, otherwise false.
    def _find(self, value):
        """(Internal Function) Returns true if a node in the BinaryTree has the value being search
           for"""

        return True if self.find_node(value) else False





    ##########
    # Delete #
    ##########
    
    # wrapper for _delete. This one is more justifiable to me than the "find" wrapper because _delete
    # is more than a single line return.
    def delete(self, value):
        """Delete the node with "value" if in the BinaryTree. Otherwise, do nothing."""

        if self.find(value):
            self._delete(value)

    def _delete(self, value):
        """Delete the node with "value" from the tree and maintain complete binary tree"""

        # if single element tree and value matches root then delete root. otherwise call function
        # _replace_node_value which replaces the value of the node to delete with the value from the
        # deepest node then delete the deepest node.
        if self.root.size == 0 and self.root.value == value:
            self.root = None
        else:
            self._replace_node_value(old=self.find_node(value), new=self._find_deepest_node())


    # interestingly, when you find the insertion point, you find the parent of the deepest node. if
    # that parent has a right_node that's the deepest, otherwise the left_node.
    def _find_deepest_node(self):
        """Return the deepest node from the tree"""

        parent = self._get_insertion_point()
        return parent.left_node if parent.right_node is None else parent.right_node


    # takes the node you wanna replace, old, and the node to replace it with, new, then replaces the
    # value in old with new, removes all the pointers to/from new, and decrements the size of the
    # parent of new (because the node is being removed)
    def _replace_node_value(self, old, new):
        """Replace the value of the first argument with the value of the second, and delete the second
           from the BinaryTree"""

        if old is None or new is None:
            print("Error: either the replacing node or the node to be replaced is None")
            return None

        old.value = new.value

        if new.parent.left_node is new:
            new.parent.left_node = None
        elif new.parent.right_node is new:
            new.parent.right_node = None

        new.parent.size -= 1
        new.parent = None





