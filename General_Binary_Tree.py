class TestFind(unittest.TestCase):
    """TESTING: Unit tests for the BinaryTree's Find Function"""

    def test_empty_tree(self):
        """TESTING: Searching empty BinaryTree"""

        tree = BinaryTree()

        self.assertEqual(tree.find(1), False)


    def test_single_node_item_found(self):
        """TESTING: Searching BinaryTree with a single element that contains element"""

        tree = BinaryTree([1])

        self.assertEqual(tree.find(1), True)


    def test_single_node_item_not_found(self):
        """TESTING: Searching BinaryTree with a single element that does not contain element"""

        tree = BinaryTree([1])

        self.assertEqual(tree.find(2), False)


    def test_item_found(self):
        """TESTING: Searching average BinaryTree that contains element"""

        tree = BinaryTree([1,2,3,4])

        self.assertEqual(tree.find(3), True)


    def test_item_not_found(self):
        """TESTING: Searching average BinaryTree that does not contain element"""

        tree = BinaryTree([1,2,3,4])

        self.assertEqual(tree.find(5), False)



class TestDelete(unittest.TestCase):
    """TESTING: Unit tests for the BinaryTree's Delete Function"""

    def test_delete_empty_tree(self):
        """TESTING: Deleting a value from an empty BinaryTree"""

        tree = BinaryTree()
        tree.delete(1)

        self.assertEqual(tree.root, None)


    def test_delete_root(self):
        """TESTING: Deleting the root element from a BinaryTree with a single element"""

        tree = BinaryTree([1])
        tree.delete(1)

        self.assertEqual(tree.find(1), False)


    def test_delete_root_longer_tree(self):
        """TESTING: Deleting the root element from a longer BinaryTree"""

        tree = BinaryTree([1,2,3,4,5,6,7,8])
        tree.delete(1)

        # most of the tests that insert/delete elements from a tree use the list generated by the
        # values_to_list function with order=level. This makes the test cases more succinct and the
        # level order makes the lists to compare them to easier to write. the generators have unit
        # tests below that should verify their output.
        self.assertEqual(tree.values_to_list(order="level"), [8,2,3,4,5,6,7])


    def test_delete_middle_longer_tree(self):
        """TESTING: Deleting a middle element from a longer BinaryTree"""

        tree = BinaryTree([1,2,3,4,5,6,7,8])
        tree.delete(4)

        self.assertEqual(tree.values_to_list(order="level"), [1,2,3,8,5,6,7])


    def test_delete_tail_longer_tree(self):
        """TESTING: Deleting the last element from a longer BinaryTree"""

        tree = BinaryTree([1,2,3,4,5,6,7,8])
        tree.delete(8)

        self.assertEqual(tree.values_to_list(order="level"), [1,2,3,4,5,6,7])
        



